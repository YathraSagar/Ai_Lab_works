import heapq

class PuzzleState:
    def __init__(self, board, parent=None, move="", depth=0):
        self.board = board  # 1D tuple of length 9
        self.parent = parent
        self.move = move
        self.depth = depth
        self.heuristic = self.calculate_manhattan()
        self.cost = self.depth + self.heuristic

    def __lt__(self, other):
        return self.cost < other.cost

    def calculate_manhattan(self):
        # Goal positions for each number 1-8. 0 is the empty tile.
        goal_positions = {
            1: (0, 0), 2: (0, 1), 3: (0, 2),
            4: (1, 0), 5: (1, 1), 6: (1, 2),
            7: (2, 0), 8: (2, 1), 0: (2, 2)
        }
        distance = 0
        for i, val in enumerate(self.board):
            if val != 0:
                curr_row, curr_col = divmod(i, 3)
                goal_row, goal_col = goal_positions[val]
                distance += abs(curr_row - goal_row) + abs(curr_col - goal_col)
        return distance

    def get_neighbors(self):
        neighbors = []
        zero_idx = self.board.index(0)
        row, col = divmod(zero_idx, 3)

        moves = {
            "Up": (-1, 0),
            "Down": (1, 0),
            "Left": (0, -1),
            "Right": (0, 1)
        }

        for direction, (dr, dc) in moves.items():
            new_row, new_col = row + dr, col + dc
            if 0 <= new_row < 3 and 0 <= new_col < 3:
                new_zero_idx = new_row * 3 + new_col
                new_board = list(self.board)
                # Swap 0 with the target cell
                new_board[zero_idx], new_board[new_zero_idx] = new_board[new_zero_idx], new_board[zero_idx]
                neighbors.append(PuzzleState(tuple(new_board), self, direction, self.depth + 1))
        return neighbors

def solve_8_puzzle(initial_board):
    goal_state = (1, 2, 3, 4, 5, 6, 7, 8, 0)
    start_state = PuzzleState(initial_board)

    open_set = []
    heapq.heappush(open_set, start_state)
    closed_set = set()

    while open_set:
        current_state = heapq.heappop(open_set)

        if current_state.board == goal_state:
            # Reconstruct path
            path = []
            curr = current_state
            while curr.parent:
                path.append((curr.move, curr.board))
                curr = curr.parent
            path.reverse()
            return path

        closed_set.add(current_state.board)

        for neighbor in current_state.get_neighbors():
            if neighbor.board in closed_set:
                continue
            # We push all neighbors; heapq will handle the priority based on f-cost (depth + heuristic)
            heapq.heappush(open_set, neighbor)

    return None

def print_board(board):
    for i in range(0, 9, 3):
        print(board[i:i+3])
    print()

# Example usage:
# 0 represents the empty space
initial_state = (1, 2, 3,  0, 5, 6, 4, 7,8)

print("Initial State:")
print_board(initial_state)

solution = solve_8_puzzle(initial_state)

if solution:
    print(f"Solved in {len(solution)} moves:")
    for step, (move, board) in enumerate(solution, 1):
        print(f"Step {step}: Move {move}")
        print_board(board)
else:
    print("No solution found.")